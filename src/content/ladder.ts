// The puzzle ladder: trainer puzzles beyond the lessons, getting harder step by step.
// Each one layers course ideas (tempo, line-up, stack timing, racing…) on top of exact combat math.
// Every puzzle is checked by the test suite: the solution must win against the AI's best defense,
// and each tempting wrong line must fail. The brute-force solver also confirms a puzzle has few winning lines.

export interface LadderPuzzle {
  /** Stable id, e.g. "ladder:tap-down". */
  id: string;
  /** The lesson whose idea the puzzle trains (linked from the trainer). */
  lessonId: string;
  ex: BoardExercise;
}

const P = (id: string, lessonId: string, ex: BoardExercise): LadderPuzzle => ({ id: `ladder:${id}`, lessonId, ex });

